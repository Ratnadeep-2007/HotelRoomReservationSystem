    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        // TODO add your handling code here:
        DBConnect x= new DBConnect();
        try{
        Connection con=x.dbCon();
        if(con== null){
        JOptionPane.showMessageDialog(null, "Unable to establilsh");
        return;
        }
        
        
        sid=txtSID.getText();
        sname=txtSName.getText();
        batch=cmbSBatch.getSelectedItem().toString();
        mob=txtSContactnumber.getText();
        addr=taAddress.getText();
        str="insert into student values(?,?,?,?,?)";
        PreparedStatement ps=con.prepareStatement(str);
        ps.setString(1,sid);
        ps.setString(2,sname);
        ps.setString(3,batch);
        ps.setString(4,addr);
        ps.setString(5,mob);
        
        int k=ps.executeUpdate();
        if(k>0){
            JOptionPane.showMessageDialog(null,"Record added");
        }
        else{
            JOptionPane.showMessageDialog(null,"Retry");
        }
        
        }
        catch(HeadlessException | SQLException e){
        
      
        }
    }//GEN-LAST:event_btnSubmitActionPerformed

